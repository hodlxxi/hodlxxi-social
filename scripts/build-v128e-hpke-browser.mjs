#!/usr/bin/env node

import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));
const outputFile = fileURLToPath(
  new URL("../web/vendor/hpke-core-v1.9.0.mjs", import.meta.url)
);

await build({
  absWorkingDir: repositoryRoot,
  banner: {
    js: "// Generated by scripts/build-v128e-hpke-browser.mjs from @hpke/core 1.9.0; MIT notice: ./hpke-js-MIT-LICENSE.txt; do not edit."
  },
  bundle: true,
  charset: "utf8",
  entryNames: "hpke-core-v1.9.0",
  format: "esm",
  legalComments: "inline",
  logLevel: "warning",
  minify: false,
  outfile: outputFile,
  platform: "browser",
  plugins: [{
    name: "disable-node-crypto-fallback",
    setup(context) {
      context.onResolve({ filter: /^crypto$/ }, () => ({
        namespace: "hodlxxi-browser-only",
        path: "crypto"
      }));
      context.onLoad(
        { filter: /^crypto$/, namespace: "hodlxxi-browser-only" },
        () => ({
          contents: "export const webcrypto = undefined;",
          loader: "js"
        })
      );
    }
  }],
  sourcemap: false,
  stdin: {
    contents: `export {
  Aes128Gcm,
  CipherSuite,
  DhkemX25519HkdfSha256,
  HkdfSha256
} from "@hpke/core";`,
    loader: "js",
    resolveDir: repositoryRoot,
    sourcefile: "hpke-core-v1.9.0-entry.mjs"
  },
  target: ["chrome111"]
});
